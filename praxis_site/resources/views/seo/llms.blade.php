# JBS Praxis

> {{ __('pages.home.description', [], 'en') }}

JBS Praxis is a consulting and engineering firm for Africa's institutions, with offices in Lagos (Nigeria) and Douala (Cameroon). It works in English and French. It designs how an organisation runs, then builds the system that runs it: finance (invoicing, payments, ledger, reporting, forecasts and financial models under IFRS and OHADA), people (payroll, time, leave, approvals), operations (projects, stock, deliveries, field teams), risk and governance (roles, permissions, audit logs, controls) and data and AI (Praxis AI answers questions from the organisation's own data and cites its sources). Clients own the code and the data; there are no per-user licences and no prices on the site. Engagements start with a free audit and demo.

The way of working is the Praxis Method (formerly the Praxis Framework): See, Design, Build, Hold.

