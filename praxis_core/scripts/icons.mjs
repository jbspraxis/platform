// Writes resources/js/icons.js: only the Lucide icons the views use (data-lucide="name", including the
// quoted names inside a Blade expression or a setAttribute call). Runs before every build (npm run build).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import * as lucide from 'lucide';

const VIEWS = 'resources/views';
const pascal = (n) => n.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const walk = (dir) => readdirSync(dir, { withFileTypes: true })
    .flatMap((d) => d.isDirectory() ? walk(join(dir, d.name)) : d.name.endsWith('.php') ? [join(dir, d.name)] : []);

const names = new Set();
for (const file of walk(VIEWS)) {
    const src = readFileSync(file, 'utf8');
    // The attribute's own quote ends the value, so a name quoted the other way inside a Blade
    // expression stays in it: data-lucide="{{ $on ? 'eye' : 'eye-off' }}" gives eye and eye-off
    for (const [, quote, value] of src.matchAll(/data-lucide=(["'])(.*?)\1/g)) {
        if (value.includes('{{')) {
            const inner = quote === '"' ? /'([a-z0-9-]+)'/g : /"([a-z0-9-]+)"/g;
            for (const [, n] of value.matchAll(inner)) names.add(n);
        } else if (value.trim()) {
            names.add(value.trim());
        }
    }
    for (const [, n] of src.matchAll(/setAttribute\(\s*'data-lucide'\s*,\s*'([a-z0-9-]+)'\s*\)/g)) names.add(n);
}

// HQ's navigation names its icons in PHP (app/Support/HqNav.php): each section()'s fourth argument, and barIcon
const nav = readFileSync('app/Support/HqNav.php', 'utf8');
for (const [, n] of nav.matchAll(/self::section\(\s*'[^']*',\s*'[^']*',\s*'[^']*',\s*'([a-z0-9-]+)'/g)) names.add(n);
for (const [, n] of nav.matchAll(/barIcon:\s*'([a-z0-9-]+)'/g)) names.add(n);

const found = [], missing = [];
for (const n of [...names].sort()) (lucide[pascal(n)] ? found : missing).push(n);
if (missing.length) console.warn(`icons.mjs: not in lucide, left out: ${missing.join(', ')}`);

writeFileSync('resources/js/icons.js',
    '// Generated by scripts/icons.mjs from the views: only the icons the screens use. Do not edit.\n'
    + `import { ${found.map(pascal).join(', ')} } from 'lucide';\n\n`
    + `export default { ${found.map(pascal).join(', ')} };\n`);
console.log(`icons.mjs: ${found.length} icons`);
